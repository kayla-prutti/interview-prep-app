create extension if not exists pgcrypto;

create table public.interviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  company text not null,
  role text not null,
  notes text not null default '',
  interviewer_type text not null check (interviewer_type in ('recruiter', 'hiring_manager', 'technical')),
  interview_date date,
  created_at timestamptz not null default now(),
  unique (id, user_id)
);

create table public.questions (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  interview_id bigint not null,
  question_text text not null,
  created_at timestamptz not null default now(),
  constraint questions_interview_owner_fk foreign key (interview_id, user_id) references public.interviews(id, user_id) on delete cascade,
  unique (id, user_id)
);

create table public.practice_interviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  company text not null,
  role text not null,
  notes text not null default '',
  interviewer_type text not null check (interviewer_type in ('recruiter', 'hiring_manager', 'technical')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, user_id)
);

create table public.practice_questions (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  practice_interview_id bigint not null,
  source_question_id bigint references public.questions(id) on delete set null,
  question_text text not null,
  answer text not null default '',
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint practice_questions_interview_owner_fk foreign key (practice_interview_id, user_id) references public.practice_interviews(id, user_id) on delete cascade,
  unique (practice_interview_id, source_question_id)
);

create index questions_user_id_idx on public.questions(user_id);
create index practice_interviews_user_id_idx on public.practice_interviews(user_id);
create index practice_questions_user_id_idx on public.practice_questions(user_id);

create function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger practice_interviews_set_updated_at before update on public.practice_interviews for each row execute function public.set_updated_at();
create trigger practice_questions_set_updated_at before update on public.practice_questions for each row execute function public.set_updated_at();

