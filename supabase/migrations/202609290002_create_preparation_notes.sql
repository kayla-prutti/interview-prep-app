create table public.preparation_notes (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  title text not null check (length(trim(title)) > 0),
  content text not null check (length(trim(content)) > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, user_id)
);

create index preparation_notes_user_id_idx on public.preparation_notes(user_id);

create trigger preparation_notes_set_updated_at
before update on public.preparation_notes
for each row execute function public.set_updated_at();

alter table public.preparation_notes enable row level security;

revoke all on public.preparation_notes from anon, authenticated;
grant select, insert, update, delete on public.preparation_notes to authenticated;
grant usage, select on all sequences in schema public to authenticated;

create policy "users select own preparation notes" on public.preparation_notes for select to authenticated using ((select auth.uid()) is not null and (select auth.uid()) = user_id);
create policy "users insert own preparation notes" on public.preparation_notes for insert to authenticated with check ((select auth.uid()) is not null and (select auth.uid()) = user_id);
create policy "users update own preparation notes" on public.preparation_notes for update to authenticated using ((select auth.uid()) is not null and (select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "users delete own preparation notes" on public.preparation_notes for delete to authenticated using ((select auth.uid()) is not null and (select auth.uid()) = user_id);
